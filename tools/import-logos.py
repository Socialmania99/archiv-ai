#!/usr/bin/env python3
"""Import a folder of logos (named after tools) into icons/tools and content/icon-map.js.
Usage: import-logos.py <folder> <name-map.json>   (map: filename -> registry id)"""
import json, re, shutil, sys, os
from PIL import Image
src, mapf = sys.argv[1], sys.argv[2]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, 'icons', 'tools'); os.makedirs(out, exist_ok=True)
m = json.load(open(mapf))
iconmap = open(os.path.join(root, 'content', 'icon-map.js')).read()
existing = dict(re.findall(r'"([^"]+)": "([^"]+)"', iconmap))
added, skipped = [], []
for f, tid in m.items():
    p = os.path.join(src, f); ext = f.rsplit('.', 1)[-1].lower()
    if ext == 'svg':
        txt = open(p, encoding='utf-8', errors='ignore').read()
        if re.search(r'<script|on\w+\s*=|javascript:|<foreignObject', txt, re.I): skipped.append((f, 'unsafe svg')); continue
        dst = f'icons/tools/{tid}.svg'; shutil.copy(p, os.path.join(root, dst))
    else:
        im = Image.open(p)
        if min(im.size) < 8: skipped.append((f, 'too small')); continue
        im = im.convert('RGBA'); w, h = im.size
        s = 128 / max(w, h) if max(w, h) > 128 else (64 / max(w, h) if max(w, h) < 64 else 1)
        if s != 1: im = im.resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS)
        dst = f'icons/tools/{tid}.png'; im.save(os.path.join(root, dst), optimize=True)
    existing[tid] = dst; added.append(tid)
body = ',\n'.join(f' "{k}": "{v}"' for k, v in sorted(existing.items()))
open(os.path.join(root, 'content', 'icon-map.js'), 'w').write(
 '// Generated by tools/build-icons.mjs + tools/import-logos.py. id -> bundled brand icon (shown on a white tile).\n'
 '// Logos are trademarks of their owners and are used only to identify each service.\n'
 '(globalThis.CV = globalThis.CV || {}).ICONS = {\n' + body + '\n};\n')
print('added', len(added), 'skipped', skipped, 'total icons', len(existing))
